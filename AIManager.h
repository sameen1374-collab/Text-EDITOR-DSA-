#ifndef AI_MANAGER_H
#define AI_MANAGER_H

#include <string>

// Structure to return results from any AI operation.
// Encapsulates success status, the generated text, and any error message.
struct AIResult {
    bool success;         // true if the request completed and returned valid text
    std::string text;     // The response text generated by the AI
    std::string error;    // Descriptive, user-friendly error message if success is false
};

// AIManager: Manages all interactions with the Google Gemini AI service.
// Uses libcurl for secure HTTPS communication and nlohmann/json for JSON handling.
class AIManager {
public:
    // Core prompt dispatcher: sends a user prompt with optional document context.
    static AIResult generate(const std::string& prompt, const std::string& context = "");

    // Utility: Checks if the GEMINI_API_KEY environment variable is currently set.
    static bool isKeyConfigured();

    // High-level feature methods (all use the same underlying network pipeline):
    // 1. General Q&A with optional document context
    static AIResult ask(const std::string& question, const std::string& docContext = "");

    // 2. Summarize document or selected text
    static AIResult summarize(const std::string& textToSummarize);

    // 3. Explain concepts or difficult passages
    static AIResult explain(const std::string& textToExplain);

    // 4. Extract bullet-point key takeaways
    static AIResult generateKeyPoints(const std::string& text);

    // 5. Detect and explain grammar/spelling errors with corrections
    static AIResult checkGrammar(const std::string& textToCheck);

    // 6. Enhance clarity, vocabulary, and flow
    static AIResult improveWriting(const std::string& textToImprove);

private:
    // Internal HTTPS dispatcher: performs the network request via libcurl
    static AIResult sendRequest(const std::string& fullPrompt);

    // libcurl write callback to collect streamed response chunks into a std::string
    static size_t writeCallback(void* contents, size_t size, size_t nmemb, void* userp);

    // Constants for the Gemini API
    static const std::string API_ENDPOINT;
    static const std::string MODEL_NAME;
};

#endif // AI_MANAGER_H
